"""Render tmp/final_exp/metrics.json as tables."""
import json
import sys

D = json.load(open("tmp/final_exp/metrics.json"))
arms = sys.argv[1:] or list(D)
NAN = float("nan")


def g(d, *path, default=NAN):
    for k in path:
        if d is None:
            return default
        d = d.get(k) if isinstance(d, dict) else None
    return default if d is None else d


print("=" * 108)
print("TABLE 1  FIXED BENCHMARK (identical positions for every arm; 2789 win-in-1, 6000 must-block)")
print("          win-in-1: mover can complete 4 -> true value +1. constant-zero predictor scores MSE 1.000")
print("=" * 108)
print(f"{'arm':<11}{'gen':>4} | {'mean V':>8} {'V>0':>7} {'V>0.9':>7} {'MSE+1':>8} | "
      f"{'winPolTop1':>11} {'blockTop1':>10} | {'games':>6} {'len':>6} {'p-1':>6} {'draw':>6} {'p+1':>6}")
for a in arms:
    for r in D.get(a, []):
        print(f"{a:<11}{r['gen']:>4} | "
              f"{g(r,'fixed','value','mean_V'):>+8.3f} {g(r,'fixed','value','frac_gt0'):>7.1%} "
              f"{g(r,'fixed','value','frac_gt09'):>7.1%} {g(r,'fixed','value','mse_vs_plus1'):>8.3f} | "
              f"{g(r,'fixed','win_policy','top1'):>11.1%} {g(r,'fixed','block_policy','top1'):>10.1%} | "
              f"{g(r,'selfplay','games'):>6.0f} {g(r,'selfplay','avg_len'):>6.1f} "
              f"{g(r,'selfplay','p_minus1'):>6.1%} {g(r,'selfplay','draw'):>6.1%} "
              f"{g(r,'selfplay','p_plus1'):>6.1%}")
    print()
print("  random-policy baselines on this set: win top1 51.4%, must-block top1 30.6%")

print()
print("=" * 108)
print("TABLE 2  OWN DATA (each arm's own generation-g positions; on-distribution, held out for model g)")
print("=" * 108)
print(f"{'arm':<11}{'gen':>4} | {'n_win':>6} {'mean V':>8} {'V>0':>7} {'V>0.9':>7} {'MSE+1':>8} | "
      f"{'winPolTop1':>11} {'n_blk':>6} {'blockTop1':>10}")
for a in arms:
    for r in D.get(a, []):
        print(f"{a:<11}{r['gen']:>4} | {g(r,'own','n_win'):>6.0f} "
              f"{g(r,'own','value','mean_V'):>+8.3f} {g(r,'own','value','frac_gt0'):>7.1%} "
              f"{g(r,'own','value','frac_gt09'):>7.1%} {g(r,'own','value','mse_vs_plus1'):>8.3f} | "
              f"{g(r,'own','win_policy','top1'):>11.1%} {g(r,'own','n_blk'):>6.0f} "
              f"{g(r,'own','block_policy','top1'):>10.1%}")
    print()

print("=" * 108)
print("TABLE 3  VALUE LOSS: train vs in-window holdout vs NEXT generation")
print("  train/val = the run's own training log at the epoch ModelCheckpoint kept (game-level split)")
print("  in-window = model g's value MSE on generation g-1 (inside its training window -> a FIT number)")
print("  next      = model g's value MSE on generation g (generated BY model g, outside its window)")
print("  both MSEs on dedup-averaged targets with occurrence weights, the same objective as val")
print("=" * 108)
print(f"{'arm':<11}{'gen':>4} | {'trainVal':>9} {'valVal':>8} {'in-window':>10} {'next':>8} | "
      f"{'next/val':>9} {'next/inwin':>11} | {'predStd':>8} {'tgtVar':>7}")
for a in arms:
    for r in D.get(a, []):
        print(f"{a:<11}{r['gen']:>4} | {g(r,'train','train_value_loss'):>9.4f} "
              f"{g(r,'train','val_value_loss'):>8.4f} {g(r,'inwin','mse_weighted'):>10.4f} "
              f"{g(r,'nxt','mse_weighted'):>8.4f} | {g(r,'gap'):>9.2f} {g(r,'gap_fit'):>11.2f} | "
              f"{g(r,'nxt','pred_std'):>8.3f} {g(r,'nxt','target_var'):>7.3f}")
    print()

print("=" * 108)
print("TABLE 4  POSITION COVERAGE -- fraction of generation g's positions that appear anywhere in the")
print("         window model g was trained on (generations g-4..g-1). Board-identity keys.")
print("=" * 108)
print(f"{'arm':<11}{'gen':>4} | {'all':>7} {'0-5':>7} {'6-9':>7} {'10-13':>7} {'14-17':>7} {'18+':>7} | "
      f"{'uniq pos':>9} {'state-key':>9}")
for a in arms:
    for r in D.get(a, []):
        c = r.get("coverage")
        if not c:
            continue
        print(f"{a:<11}{r['gen']:>4} | {c['board']:>7.1%} " +
              " ".join(f"{c.get('band_' + b, NAN):>7.1%}" for b in
                       ["0-5", "6-9", "10-13", "14-17", "18+"]) +
              f" | {c['n_positions']:>9} {c['state']:>9.1%}")
    print()
